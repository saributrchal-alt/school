-- Safe to repeat: existing rows are retained; no DROP, TRUNCATE or DELETE statements.
-- The final query shows expected/actual counts and a passed flag.
--
-- MEMBER BRIDGE: follow the existing Temple -> Account server-to-server pattern.
-- Temple remains the source of member identity. School uses the SAME member_id as text.
-- Destination record: member_id, member_name, can_study, can_teach, can_manage,
--                     is_active, assigned_by, assigned_at, updated_at.
-- POST payload to the future School receiver includes those fields (timestamps set by server).
-- School's server verifies HMAC-SHA256 with SCHOOL_BRIDGE_KEY before importing a member.
-- Use the same SCHOOL_BRIDGE_KEY on Temple and School servers; do not send it to the browser.
-- Import by UPSERT on school_members.member_id, and log the grant/revocation in
-- school_member_bridge_events. Revocation sets is_active=false; it retains learning history.
-- A 5-minute signed handoff is exchanged for School's own 4-hour HttpOnly session.
-- Server must check current is_active and permissions on each protected request.
-- This SQL prepares the database. The bridge receiver, sender and session code are separate.
-- It does not transfer live members or deploy the bridge by itself.
-- No member/password/LINE/Telegram data is seeded, and no cross-project FK is required.

BEGIN;
SET LOCAL standard_conforming_strings = on;

CREATE TABLE IF NOT EXISTS public.exam_subjects_master (
    subject_id text PRIMARY KEY,
    subject_name_th text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.exam_sources (
    source_id text PRIMARY KEY,
    filename text NOT NULL,
    pdf_page_count integer NOT NULL CHECK (pdf_page_count > 0),
    sha256 text NOT NULL
);

CREATE TABLE IF NOT EXISTS public.exam_sets (
    exam_id text PRIMARY KEY,
    year_be integer UNIQUE NOT NULL,
    exam_date date,
    question_count integer NOT NULL CHECK (question_count > 0),
    duration_minutes integer CHECK (duration_minutes > 0),
    cover_pdf_page integer CHECK (cover_pdf_page > 0),
    max_points_general integer,
    max_points_special integer
);

CREATE TABLE IF NOT EXISTS public.exam_subject_weights (
    exam_id text NOT NULL REFERENCES public.exam_sets (exam_id),
    subject_id text NOT NULL REFERENCES public.exam_subjects_master (subject_id),
    question_start integer NOT NULL CHECK (question_start > 0),
    question_end integer NOT NULL,
    question_count integer NOT NULL CHECK (question_count > 0),
    points_per_question_general integer NOT NULL,
    max_points_general integer NOT NULL,
    points_per_question_special integer,
    max_points_special integer,
    PRIMARY KEY (exam_id, subject_id),
    CHECK (question_end = question_start + question_count - 1)
);

CREATE TABLE IF NOT EXISTS public.exam_chapters (
    chapter_id text PRIMARY KEY,
    subject_id text NOT NULL REFERENCES public.exam_subjects_master (subject_id),
    chapter_name_th text NOT NULL,
    discipline_th text,
    sort_order integer NOT NULL CHECK (sort_order > 0)
);

CREATE TABLE IF NOT EXISTS public.exam_topics (
    topic_id text PRIMARY KEY,
    chapter_id text NOT NULL REFERENCES public.exam_chapters (chapter_id),
    subject_id text NOT NULL REFERENCES public.exam_subjects_master (subject_id),
    topic_slug text UNIQUE NOT NULL,
    topic_name_th text NOT NULL,
    sort_order integer NOT NULL CHECK (sort_order > 0)
);

CREATE TABLE IF NOT EXISTS public.exam_questions (
    question_id text PRIMARY KEY,
    source_id text NOT NULL REFERENCES public.exam_sources (source_id),
    exam_id text NOT NULL REFERENCES public.exam_sets (exam_id),
    year_be integer NOT NULL,
    subject_id text NOT NULL REFERENCES public.exam_subjects_master (subject_id),
    exam_question_no integer NOT NULL CHECK (exam_question_no > 0),
    subject_question_no integer NOT NULL CHECK (subject_question_no > 0),
    primary_topic_id text NOT NULL REFERENCES public.exam_topics (topic_id),
    content_focus_th text NOT NULL,
    pdf_pages jsonb NOT NULL,
    printed_pages jsonb NOT NULL,
    answer_key integer CHECK (answer_key BETWEEN 1 AND 5),
    answer_key_pdf_page integer CHECK (answer_key_pdf_page > 0),
    answer_key_status text NOT NULL,
    tagging_method text NOT NULL,
    UNIQUE (exam_id, exam_question_no),
    UNIQUE (exam_id, subject_id, subject_question_no)
);

CREATE TABLE IF NOT EXISTS public.exam_question_topics (
    question_id text NOT NULL REFERENCES public.exam_questions (question_id),
    topic_id text NOT NULL REFERENCES public.exam_topics (topic_id),
    role text NOT NULL CHECK (role IN ('primary', 'related')),
    PRIMARY KEY (question_id, topic_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS one_primary_topic_per_question
    ON public.exam_question_topics (question_id) WHERE role = 'primary';
CREATE INDEX IF NOT EXISTS exam_questions_year_subject_idx
    ON public.exam_questions (year_be, subject_id);
CREATE INDEX IF NOT EXISTS exam_questions_primary_topic_idx
    ON public.exam_questions (primary_topic_id);
CREATE INDEX IF NOT EXISTS exam_question_topics_topic_idx
    ON public.exam_question_topics (topic_id, role);
CREATE INDEX IF NOT EXISTS exam_chapters_subject_idx
    ON public.exam_chapters (subject_id, sort_order);
CREATE INDEX IF NOT EXISTS exam_topics_chapter_idx
    ON public.exam_topics (chapter_id, sort_order);

-- School member identity is imported from the Temple, as account_staff is in Account.
-- This is not the Temple's existing temple_student/chores login system.
CREATE TABLE IF NOT EXISTS public.school_members (
    member_id text PRIMARY KEY CHECK (length(btrim(member_id)) BETWEEN 1 AND 100),
    member_name text NOT NULL CHECK (length(btrim(member_name)) > 0),
    can_study boolean NOT NULL DEFAULT true,
    can_teach boolean NOT NULL DEFAULT false,
    can_manage boolean NOT NULL DEFAULT false,
    is_active boolean NOT NULL DEFAULT true,
    assigned_by text NOT NULL CHECK (length(btrim(assigned_by)) BETWEEN 1 AND 100),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- Append one record for each successful signed import or revocation.
-- assigned_by is a Temple member ID; it is not a foreign key across Supabase projects.
CREATE TABLE IF NOT EXISTS public.school_member_bridge_events (
    event_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    member_id text NOT NULL REFERENCES public.school_members (member_id),
    assigned_by text NOT NULL CHECK (length(btrim(assigned_by)) BETWEEN 1 AND 100),
    action text NOT NULL CHECK (action IN ('upsert', 'deactivate')),
    can_study boolean NOT NULL,
    can_teach boolean NOT NULL,
    can_manage boolean NOT NULL,
    is_active boolean NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS school_member_bridge_events_member_idx
    ON public.school_member_bridge_events (member_id, received_at DESC);

-- No fabricated progress or attempts are seeded. Values come from actual activity.
CREATE TABLE IF NOT EXISTS public.school_topic_progress (
    member_id text NOT NULL REFERENCES public.school_members (member_id),
    topic_id text NOT NULL REFERENCES public.exam_topics (topic_id),
    status text NOT NULL DEFAULT 'not_started'
        CHECK (status IN ('not_started', 'in_progress', 'review', 'completed')),
    notes text NOT NULL DEFAULT '',
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (member_id, topic_id)
);
CREATE INDEX IF NOT EXISTS school_topic_progress_topic_idx
    ON public.school_topic_progress (topic_id);

CREATE TABLE IF NOT EXISTS public.school_question_attempts (
    attempt_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    member_id text NOT NULL REFERENCES public.school_members (member_id),
    question_id text NOT NULL REFERENCES public.exam_questions (question_id),
    selected_answer integer NOT NULL CHECK (selected_answer BETWEEN 1 AND 5),
    is_correct boolean,
    elapsed_seconds integer CHECK (elapsed_seconds >= 0),
    attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS school_question_attempts_member_idx
    ON public.school_question_attempts (member_id, attempted_at DESC);
CREATE INDEX IF NOT EXISTS school_question_attempts_question_idx
    ON public.school_question_attempts (question_id);

