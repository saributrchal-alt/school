-- Verification: all 12 rows below should have passed = true.
-- Counts are limited to this source, so later exam imports do not inflate them.
WITH source_questions AS (
    SELECT * FROM public.exam_questions
    WHERE source_id = 'EX62_63' AND exam_id IN ('EX2562', 'EX2563')
), source_links AS (
    SELECT qt.* FROM public.exam_question_topics qt
    JOIN source_questions q ON q.question_id = qt.question_id
), source_topics AS (
    SELECT DISTINCT t.* FROM public.exam_topics t
    JOIN source_links qt ON qt.topic_id = t.topic_id
), checks AS (
    SELECT 1 AS sort_order, 'subjects' AS item, 5 AS expected,
           (SELECT count(DISTINCT subject_id) FROM source_questions) AS actual
    UNION ALL SELECT 2, 'chapters', 64,
           (SELECT count(DISTINCT chapter_id) FROM source_topics)
    UNION ALL SELECT 3, 'topics', 261, (SELECT count(*) FROM source_topics)
    UNION ALL SELECT 4, 'exam_sets', 2,
           (SELECT count(DISTINCT exam_id) FROM source_questions)
    UNION ALL SELECT 5, 'questions_total', 440, (SELECT count(*) FROM source_questions)
    UNION ALL SELECT 6, 'questions_2562', 215,
           (SELECT count(*) FROM source_questions WHERE year_be = 2562)
    UNION ALL SELECT 7, 'questions_2563', 225,
           (SELECT count(*) FROM source_questions WHERE year_be = 2563)
    UNION ALL SELECT 8, 'primary_links', 440,
           (SELECT count(*) FROM source_links WHERE role = 'primary')
    UNION ALL SELECT 9, 'related_links', 59,
           (SELECT count(*) FROM source_links WHERE role = 'related')
    UNION ALL SELECT 10, 'answer_keys', 440,
           (SELECT count(*) FROM source_questions WHERE answer_key BETWEEN 1 AND 5)
    UNION ALL SELECT 11, 'questions_missing_primary', 0,
           (SELECT count(*) FROM source_questions q WHERE NOT EXISTS (
               SELECT 1 FROM source_links qt
               WHERE qt.question_id = q.question_id AND qt.role = 'primary'
                 AND qt.topic_id = q.primary_topic_id
           ))
    UNION ALL SELECT 12, 'questions_subject_mismatch', 0,
           (SELECT count(*) FROM source_questions q
            JOIN public.exam_topics t ON t.topic_id = q.primary_topic_id
            WHERE q.subject_id <> t.subject_id)
)
SELECT item, expected, actual, actual = expected AS passed
FROM checks ORDER BY sort_order;
